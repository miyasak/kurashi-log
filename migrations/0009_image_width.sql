## 川の音がする

<a href="/media/uploads/1792922783570-h9kzpf.png" target="_blank" rel="noopener"><img src="/media/uploads/1792922783570-h9kzpf.png" alt="キャンプ場のそばを流れる松川" style="width:260px;border-radius:10px;"></a>

すぐ近くを松川が流れていて、サイトまで水の音が届く。

夜になると、音が川だけになる瞬間がある。無料のキャンプ場でそれが手に入る場所は、そう多くない。

