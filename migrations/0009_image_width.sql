## 入道崎

<p><a href="/media/uploads/1793368633712-kj9458.png" target="_blank" rel="noopener"><img src="/media/uploads/1793368633712-kj9458.png" alt="入道崎の白黒の縞模様の灯台" style="width:260px;border-radius:10px;"></a></p>

