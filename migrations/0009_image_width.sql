観光地なので人も車も多い。写真を撮るのも待ち時間が発生する。ここは「着いた」という事実が目的の場所で、長く居る場所ではないと思っている。

宗谷岬のシンボルを間近で撮影できるわけではないが、すぐ近くにある宗谷岬公園であれば宗谷湾を見渡すことができる。

