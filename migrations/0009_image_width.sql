## なぜ毎年行くのか

無料のキャンプ場はたくさんあるが、設備が綺麗で、川の音がして、買い出しも風呂も揃っていて、高速のICから10分という場所はほとんどない。

どれかひとつが欠けていても通わなかったと思う。全部そろっていて、しかも0円。たまに騒がしい夜があることを差し引いても、その計算はまだ合っている。

