大人560円。入浴は10時30分から21時、札止めは20時30分、休みは毎月第2・第4月曜日。

泉質はpH9.9のアルカリ性単純泉で、ラドンを含む。地元では「美人の湯」と呼ばれているらしい。湯に入った感触が確かにぬるっとしていて、数字どおりだった。

露天風呂やリラックススペース、休憩所や食堂もあり、これで560円は非常に安い。もし近くにあれば週に1回は通うかもしれない、かなりのお気に入り。

