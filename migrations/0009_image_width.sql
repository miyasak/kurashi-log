## 走ってみて

移動日のつもりで組んだ一日だったが、結果としては内容が濃くなった。

国道56号でまっすぐ下れば、距離は150kmほどで済んだはずだ。321号に振ったことで100km増えて、足摺岬と竜串が入った。増えたぶんは全部景色になった。

四国の南西端は、本州から行くと遠い。次にいつ来るか分からない場所なので、通過するだけにしなくて正解だったと思う。

