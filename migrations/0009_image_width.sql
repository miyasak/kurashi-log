<p><a href="/media/uploads/1793369628045-8pptm8.png" target="_blank" rel="noopener"><img src="/media/uploads/1793369628045-8pptm8.png" alt="寒風山の山頂標識と青空" style="width:260px;border-radius:10px;"></a></p>
